"""Пользовательские ошибки приложения.

Все ожидаемые проблемы (нет файла, битый XLSX, нет обязательных столбцов и т. п.)
поднимаются как :class:`DataFlowError`. CLI показывает их кратко и завершает
процесс с ненулевым кодом, не заставляя пользователя читать traceback.
"""

from __future__ import annotations


class DataFlowError(Exception):
    """Ожидаемая ошибка, сообщение которой безопасно показать пользователю."""


class InputError(DataFlowError):
    """Проблема с исходным файлом или его форматом."""


class OutputError(DataFlowError):
    """Проблема с каталогом или файлами результата."""


class NoValidRecordsError(DataFlowError):
    """После проверки не осталось ни одной корректной записи."""
